"""Local sibling overrides for the microservice workspace.

[workspace.dependencies] is the CI truth: git revisions. Sibling paths live
in [workspace.metadata.local-deps], which Cargo does not resolve. Tilt sets
RERP_LOCAL_DEPS=1 and this module writes a gitignored config that the build
tool passes to `cargo --config`. A normal `cargo build` does not see it.
"""

from __future__ import annotations

import os
import sys
import tomllib
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
WORKSPACE = REPO_ROOT / "microservices"
MANIFEST = WORKSPACE / "Cargo.toml"
LOCAL_CONFIG = WORKSPACE / ".cargo" / "local-deps.config"

# Tables whose `path` values are compiled. A path that leaves the workspace
# would make CI depend on a sibling checkout.
RELEASE_TABLES = ("dependencies", "dev-dependencies", "build-dependencies")


def load_manifest(path: Path = MANIFEST) -> dict:
    with path.open("rb") as fh:
        return tomllib.load(fh)


def release_violations(manifest: dict) -> list[str]:
    """Paths that escape the workspace in tables Cargo actually resolves."""
    errors: list[str] = []
    blocks: list[tuple[str, dict]] = []
    workspace = manifest.get("workspace") or {}
    deps = workspace.get("dependencies") or {}
    if isinstance(deps, dict):
        blocks.append(("[workspace.dependencies]", deps))
    patch = manifest.get("patch") or {}
    if isinstance(patch, dict):
        for source, crates in patch.items():
            if isinstance(crates, dict):
                blocks.append((f"[patch.{source}]", crates))
    for label, table in blocks:
        for name, spec in table.items():
            if not isinstance(spec, dict):
                continue
            raw = spec.get("path")
            if isinstance(raw, str) and raw.startswith(".."):
                errors.append(f"{label} {name} path {raw} escapes the workspace")
    return errors


def config_lines(manifest: dict, workspace: Path) -> list[str]:
    """cargo --config values for siblings that exist on disk."""
    local = (manifest.get("workspace") or {}).get("metadata", {}).get("local-deps") or {}
    lines: list[str] = []
    if not isinstance(local, dict):
        return lines
    for name, spec in local.items():
        if not isinstance(spec, dict):
            continue
        git = spec.get("git")
        rel = spec.get("path")
        if not isinstance(git, str) or not isinstance(rel, str):
            continue
        absolute = (workspace / rel).resolve()
        if not (absolute / "Cargo.toml").is_file():
            print(f"local-deps: skip {name} ({absolute} has no Cargo.toml)", file=sys.stderr)
            continue
        # cargo --config keys quote the git URL. The path is absolute so the
        # value does not depend on the caller's cwd.
        lines.append(f'patch."{git}".{name}.path="{absolute}"')
    return lines


def apply(enabled: bool, workspace: Path = WORKSPACE, manifest_path: Path = MANIFEST) -> list[str]:
    """Write or remove the gitignored config. Returns the --config lines."""
    if not enabled:
        if LOCAL_CONFIG.exists() and workspace == WORKSPACE:
            LOCAL_CONFIG.unlink()
        return []
    manifest = load_manifest(manifest_path)
    lines = config_lines(manifest, workspace if manifest_path == MANIFEST else manifest_path.parent)
    dest = workspace / ".cargo" / "local-deps.config" if workspace == WORKSPACE else manifest_path.parent / ".cargo" / "local-deps.config"
    if not lines:
        if dest.exists():
            dest.unlink()
        return []
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(
        "# Generated by local_deps.py when RERP_LOCAL_DEPS=1 (rerp_tooling). Gitignored.\n"
        "# Not loaded by cargo on its own. The build passes each line to --config.\n"
        + "\n".join(lines)
        + "\n"
    )
    return lines


def main(argv: list[str]) -> int:
    manifest = load_manifest()
    violations = release_violations(manifest)
    if "--check" in argv:
        for item in violations:
            print(item, file=sys.stderr)
        return 1 if violations else 0
    enabled = os.environ.get("RERP_LOCAL_DEPS", "0") == "1"
    lines = apply(enabled)
    if "--print-config" in argv:
        sys.stdout.write("\n".join(lines))
        if lines:
            sys.stdout.write("\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
